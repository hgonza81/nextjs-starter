/**
 * `pnpm db:schema`: regenerates the Drizzle schema mirror from the local
 * database (FND-FR-07, ADR 0002). Run it after `pnpm db:reset`.
 *
 * `drizzle-kit pull` also writes a randomly named `0000_*.sql` file and a
 * `meta/` folder (an introspection "migration" that must never be applied).
 * They are removed here so the output is stable: running this twice yields an
 * empty `git diff`. Only `schema.ts` and `relations.ts` are kept, each marked
 * as generated. `index.ts` in the same folder is hand-written and untouched.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SCHEMA_DIR = join(import.meta.dirname, "..", "src", "db", "schema");
const GENERATED_FILES = ["schema.ts", "relations.ts"] as const;
const HEADER =
  "// GENERATED by `pnpm db:schema` (drizzle-kit pull). Do not edit.\n" +
  "// Source of truth: supabase/migrations (ADR 0002).\n";

function removeGeneratedOutput(): void {
  for (const entry of readdirSync(SCHEMA_DIR)) {
    if (entry.endsWith(".sql") || entry === "meta") {
      rmSync(join(SCHEMA_DIR, entry), { recursive: true });
    }
  }
}

removeGeneratedOutput();
for (const file of GENERATED_FILES) {
  rmSync(join(SCHEMA_DIR, file), { force: true });
}

// Throws (non-zero exit) when drizzle-kit fails, e.g. database unreachable.
execFileSync("pnpm", ["exec", "drizzle-kit", "pull"], { stdio: "inherit" });

removeGeneratedOutput();
for (const file of GENERATED_FILES) {
  const path = join(SCHEMA_DIR, file);
  writeFileSync(path, HEADER + readFileSync(path, "utf8"));
}
